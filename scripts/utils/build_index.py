"""Generate knowledge/INDEX.md, the map of every note in the memex.

The index is the first thing an AI session should read: one line per note with
what it covers, how sensitive it is, and when it was last updated. It is
generated from frontmatter, so never edit it by hand.
"""

from pathlib import Path

from scripts.utils.memex_notes import Note, load_notes

HEADER = """---
date: 2026-11-02
updated: {updated}
tags: [index, meta, ledger]
status: active
summary: Generated map of every note, its sensitivity and last update. Read first.
sensitivity: private
---

# Memex Index

Generated by `uv run python -m skills.dream.skill --fix`. Do not edit by hand.

**How to use**: read this index, then open only the notes you need. `sensitivity`:
`private` (never copy into anything that leaves the memex), `usable` (may inform
things you write, e.g. a resume or a blog post, subject to the rules in
[context/PREFERENCES.md](../context/PREFERENCES.md)), `public` (already public).

Total: {count} notes, about {words:,} words.
"""

SECTION_TITLES = {
    "context": "Context (who I am, rules, goals)",
    "knowledge/projects": "Projects",
    "knowledge/people": "People",
    "knowledge/areas": "Areas",
    "knowledge/reference": "Reference",
    "knowledge/sources": "Sources and ledgers",
    "knowledge/daily": "Daily notes",
    "knowledge": "Knowledge (top level)",
}

SECTION_ORDER = list(SECTION_TITLES)


def _section_key(note: Note) -> str:
    """Return the section a note belongs in: its nearest known ancestor folder."""
    folder = note.rel.rsplit("/", 1)[0] if "/" in note.rel else ""
    while folder and folder not in SECTION_TITLES:
        folder = folder.rsplit("/", 1)[0] if "/" in folder else ""
    return folder or "knowledge"


def _updated(note: Note) -> str:
    """Return the note's 'updated' date as text."""
    return str(note.meta.get("updated") or note.meta.get("date") or "")


def build_index(repo_root: Path, notes: list[Note] | None = None) -> str:
    """Build the index markdown.

    Args:
        repo_root: Repository root.
        notes: Pre-loaded notes (loaded from disk if omitted).

    Returns:
        The full contents of knowledge/INDEX.md.
    """
    all_notes = notes if notes is not None else load_notes(repo_root)
    notes = [n for n in all_notes if n.path.name != "INDEX.md"]
    sections: dict[str, list[Note]] = {}
    for note in notes:
        sections.setdefault(_section_key(note), []).append(note)

    latest = max((_updated(n) for n in notes), default="")
    lines = [
        HEADER.format(
            updated=latest, count=len(notes), words=sum(n.words for n in notes)
        ).rstrip(),
        "",
    ]
    daily = sections.pop("knowledge/daily", [])
    for key in SECTION_ORDER + sorted(set(sections) - set(SECTION_ORDER)):
        if key not in sections:
            continue
        lines += [
            f"## {SECTION_TITLES.get(key, key)}",
            "",
            "| Note | What it covers | Sensitivity | Updated | Words |",
            "|------|----------------|-------------|---------|-------|",
        ]
        for note in sorted(sections[key], key=lambda n: n.rel):
            link = (
                Path("..") / note.rel
                if note.rel.startswith("context/")
                else Path(note.rel).relative_to("knowledge")
            )
            summary = str(note.meta.get("summary") or "").replace("|", "/")
            lines.append(
                f"| [{note.title}]({link.as_posix()}) | {summary} | "
                f"{note.meta.get('sensitivity', '?')} | {_updated(note)} | "
                f"{note.words:,} |"
            )
        lines.append("")
    if daily:
        lines += [
            "## Daily notes",
            "",
            f"{len(daily)} note(s) in [daily/](daily/); newest: "
            f"{max(n.path.stem for n in daily)}.",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def write_index(repo_root: Path) -> bool:
    """Regenerate knowledge/INDEX.md.

    Args:
        repo_root: Repository root.

    Returns:
        True if the file changed (or was created).
    """
    target = repo_root / "knowledge" / "INDEX.md"
    new = build_index(repo_root)
    old = target.read_text(encoding="utf-8") if target.exists() else ""
    if new == old:
        return False
    target.write_text(new, encoding="utf-8")
    return True
